import puppeteer from 'puppeteer-core';
import fs from 'node:fs';
const BASE = 'http://127.0.0.1:3000';
const b = await puppeteer.launch({ executablePath: '/usr/bin/chromium-browser', headless: 'shell', args: ['--no-sandbox'], defaultViewport:{width:1400,height:900}});
const out = process.argv[2] || '/tmp';
const key = fs.readFileSync('../data/bootstrap-admin.key','utf8').trim();
const ctx = await b.createBrowserContext();
const p = await ctx.newPage();
await p.goto(BASE+'/#/login', {waitUntil:'networkidle2'});
await p.waitForSelector('.login-submit');
await new Promise(r=>setTimeout(r,500));
await p.screenshot({path: out+'/login.png'});
await p.type('input.input','admin');
await p.click('textarea.key-input');
await p.type('textarea.key-input', key);
await p.click('.login-submit');
await p.waitForSelector('.app-shell');
await p.evaluate(() => {
  const row = document.querySelector('.tree-row[data-path="README.md"]');
  row && row.click();
});
await p.waitForSelector('.cm-content');
await p.waitForFunction(() => !!document.querySelector('.markdown-body svg'), {timeout:20000}).catch(()=>{});
await new Promise(r=>setTimeout(r,800));
await p.screenshot({path: out+'/editor.png'});
await p.evaluate(() => { location.hash = '#/admin'; });
await p.waitForFunction(() => document.body.innerText.includes('用户管理'), {timeout:15000}).catch(()=>{});
await new Promise(r=>setTimeout(r,600));
await p.screenshot({path: out+'/admin.png'});
console.log('screenshots written to', out);
await b.close();
